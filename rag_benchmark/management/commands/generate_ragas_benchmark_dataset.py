from __future__ import annotations

from django.core.management.base import BaseCommand, CommandError

from rag_benchmark.services.dataset_importer import (
    BenchmarkDatasetImporter,
    DatasetValidationError,
)
from rag_benchmark.services.testset_generator import RagasBenchmarkDatasetGenerator


class Command(BaseCommand):
    help = "Generate benchmark dataset JSONL from current vector-store docs via Ragas"

    def add_arguments(self, parser):
        parser.add_argument(
            "--output",
            required=True,
            help="Output JSONL file path",
        )
        parser.add_argument(
            "--size",
            type=int,
            default=20,
            help="Number of benchmark cases to synthesize",
        )
        parser.add_argument(
            "--dataset-version",
            default="v1",
            help="Dataset version field to write into each case",
        )
        parser.add_argument(
            "--dev-ratio",
            type=float,
            default=0.6,
            help="Fraction of generated cases assigned to dev split",
        )
        parser.add_argument(
            "--seed",
            type=int,
            default=42,
            help="Random seed for split shuffle",
        )
        parser.add_argument(
            "--provider",
            choices=["auto", "gemini", "openrouter"],
            default="auto",
            help="Model provider for ragas generation",
        )
        parser.add_argument(
            "--llm-model",
            default="",
            help="Override LLM model name (provider-specific)",
        )
        parser.add_argument(
            "--embedding-model",
            default="",
            help="Override embedding model name (provider-specific)",
        )
        parser.add_argument(
            "--llm-context",
            default=(
                "Generate realistic Vietnamese end-user medical questions that match "
                "the provided disease context. Keep questions concise and practical."
            ),
            help="Optional generation context prompt for ragas",
        )
        parser.add_argument(
            "--collections",
            default="medical_documents_chunks",
            help="Comma-separated physical collection names to use",
        )
        parser.add_argument(
            "--min-document-words",
            type=int,
            default=100,
            help="Minimum words per aggregated source document for ragas",
        )
        parser.add_argument(
            "--import-name",
            default="",
            help="Optional dataset name to import generated JSONL directly",
        )
        parser.add_argument(
            "--description",
            default="Generated by ragas testset generator",
            help="Description when importing to BenchmarkDataset",
        )
        parser.add_argument(
            "--activate",
            action="store_true",
            default=False,
            help="Activate imported dataset version",
        )

    def handle(self, *args, **options):
        collections = [
            item.strip()
            for item in str(options["collections"]).split(",")
            if item.strip()
        ]
        generator = RagasBenchmarkDatasetGenerator()

        try:
            report = generator.generate_jsonl(
                output_path=str(options["output"]),
                testset_size=int(options["size"]),
                dataset_version=str(options["dataset_version"]),
                dev_ratio=float(options["dev_ratio"]),
                seed=int(options["seed"]),
                provider=str(options["provider"]),
                llm_model=str(options["llm_model"]).strip() or None,
                embedding_model=str(options["embedding_model"]).strip() or None,
                llm_context=str(options["llm_context"]),
                collections=collections,
                min_document_words=int(options["min_document_words"]),
            )
        except Exception as exc:
            raise CommandError(f"Ragas dataset generation failed: {exc}") from exc

        self.stdout.write(
            self.style.SUCCESS(
                (
                    f"Generated JSONL: {report.output_path} | "
                    f"cases={report.total_cases} (dev={report.dev_cases}, test={report.test_cases}) | "
                    f"source_titles={report.source_titles}, unique_gold_titles={report.unique_gold_titles}"
                )
            )
        )

        import_name = str(options["import_name"]).strip()
        if not import_name:
            return

        importer = BenchmarkDatasetImporter()
        try:
            with open(report.output_path, "rb") as fp:
                dataset, import_report = importer.import_jsonl(
                    name=import_name,
                    version=str(options["dataset_version"]),
                    file_obj=fp,
                    description=str(options["description"]),
                    schema_version="1.0",
                    activate=bool(options["activate"]),
                )
        except FileNotFoundError as exc:
            raise CommandError(
                f"Generated file not found for import: {report.output_path}"
            ) from exc
        except DatasetValidationError as exc:
            raise CommandError(f"Generated dataset failed validation: {exc}") from exc
        except Exception as exc:
            raise CommandError(f"Dataset import failed: {exc}") from exc

        self.stdout.write(
            self.style.SUCCESS(
                (
                    f"Imported dataset {dataset.name}:{dataset.version} "
                    f"with {import_report.total_cases} cases"
                )
            )
        )
